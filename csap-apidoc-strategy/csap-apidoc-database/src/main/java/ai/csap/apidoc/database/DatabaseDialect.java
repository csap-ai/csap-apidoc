package ai.csap.apidoc.database;

import java.util.Locale;

/**
 * 数据库方言:决定建表语句里的字段类型和自增主键写法。
 *
 * <p>读写语句只用各库通用的 SQL(普通的 SELECT / INSERT / UPDATE / DELETE 和 {@code ?} 占位符),
 * 不依赖 upsert、LIMIT 等方言差异;并发保存靠"先 UPDATE 全局版本号"取得行锁串行化。
 *
 * @author ycf
 * @since 1.4.0
 */
public enum DatabaseDialect {

    /**
     * MySQL 5.7+ / 8.x,以及兼容 MySQL 协议的库(按 MySQL 方言试用)
     */
    MYSQL("LONGTEXT", "id BIGINT AUTO_INCREMENT PRIMARY KEY", " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"),
    /**
     * PostgreSQL 12+
     */
    POSTGRESQL("TEXT", "id BIGSERIAL PRIMARY KEY", ""),
    /**
     * 达梦 DM8
     */
    DM("CLOB", "id BIGINT IDENTITY(1, 1) PRIMARY KEY", ""),
    /**
     * 人大金仓 KingbaseES V8 / V9(PostgreSQL 兼容模式;库初始化为 MySQL 兼容模式时请显式指定 MYSQL)
     */
    KINGBASE("TEXT", "id BIGSERIAL PRIMARY KEY", ""),
    /**
     * SQLite 3.x(单机、开发环境)
     */
    SQLITE("TEXT", "id INTEGER PRIMARY KEY AUTOINCREMENT", ""),
    /**
     * H2(测试用)
     */
    H2("CLOB", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "");

    private final String textType;
    private final String idColumn;
    private final String tableOptions;

    DatabaseDialect(String textType, String idColumn, String tableOptions) {
        this.textType = textType;
        this.idColumn = idColumn;
        this.tableOptions = tableOptions;
    }

    /**
     * 大文本字段类型(规则 JSON)
     */
    public String textType() {
        return textType;
    }

    /**
     * 自增主键列定义
     */
    public String idColumn() {
        return idColumn;
    }

    /**
     * 建表语句末尾的选项
     */
    public String tableOptions() {
        return tableOptions;
    }

    /**
     * 根据 JDBC URL 识别方言,识别不了返回 null。
     *
     * @param jdbcUrl JDBC URL
     * @return 方言
     */
    public static DatabaseDialect fromJdbcUrl(String jdbcUrl) {
        if (jdbcUrl == null) {
            return null;
        }
        String url = jdbcUrl.toLowerCase(Locale.ROOT);
        if (url.startsWith("jdbc:mysql:") || url.startsWith("jdbc:mariadb:")) {
            return MYSQL;
        }
        if (url.startsWith("jdbc:postgresql:")) {
            return POSTGRESQL;
        }
        if (url.startsWith("jdbc:dm:")) {
            return DM;
        }
        if (url.startsWith("jdbc:kingbase8:") || url.startsWith("jdbc:kingbase:")) {
            return KINGBASE;
        }
        if (url.startsWith("jdbc:sqlite:")) {
            return SQLITE;
        }
        if (url.startsWith("jdbc:h2:")) {
            return H2;
        }
        return null;
    }

    /**
     * 按名称解析方言(不区分大小写),也接受 postgres / pg / dameng / kingbasees 等常见写法。
     *
     * @param name 名称
     * @return 方言,空字符串返回 null
     */
    public static DatabaseDialect parse(String name) {
        if (name == null || name.trim().isEmpty()) {
            return null;
        }
        String n = name.trim().toUpperCase(Locale.ROOT).replace("-", "").replace("_", "");
        switch (n) {
            case "MYSQL":
            case "MARIADB":
                return MYSQL;
            case "POSTGRESQL":
            case "POSTGRES":
            case "PG":
                return POSTGRESQL;
            case "DM":
            case "DM8":
            case "DAMENG":
                return DM;
            case "KINGBASE":
            case "KINGBASEES":
            case "KINGBASE8":
                return KINGBASE;
            case "SQLITE":
                return SQLITE;
            case "H2":
                return H2;
            default:
                throw new IllegalArgumentException("csap.apidoc.database.dialect 不支持 " + name
                        + ",可选 mysql / postgresql / dm / kingbase / sqlite / h2");
        }
    }
}
