package ai.csap.apidoc.database;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.regex.Pattern;

import javax.sql.DataSource;

import ai.csap.apidoc.model.RuleChange;
import ai.csap.apidoc.strategy.store.RuleJson;
import ai.csap.apidoc.strategy.store.RuleStore;

/**
 * 规则表的 JDBC 读写,与 csap-apidoc-go 的 SQL 规则来源共用同一套表:
 *
 * <pre>
 * {prefix}rule     规则:每个接口一行,(service, rule_key) 主键,rules 为规则 JSON
 * {prefix}history  修改记录:每次保存一行,before_rules / after_rules / version / updated_by / updated_at
 * {prefix}meta     全局版本号:每个 service 一行,每次保存加 1,其他实例轮询它判断是否需要重新加载
 * </pre>
 *
 * <p>时间为毫秒时间戳。规则为空(request、response 都没有字段)时删除该行。
 *
 * @author ycf
 * @since 1.4.0
 */
public class DatabaseRuleStore implements RuleStore {

    private static final Pattern PREFIX = Pattern.compile("[A-Za-z0-9_]*");

    private final DataSource dataSource;
    private final DatabaseDialect dialect;
    private final String service;
    private final String ruleTable;
    private final String historyTable;
    private final String metaTable;
    private final String prefix;

    public DatabaseRuleStore(DataSource dataSource, DatabaseDialect dialect, String tablePrefix, String service) {
        this.dataSource = Objects.requireNonNull(dataSource, "dataSource");
        this.dialect = Objects.requireNonNull(dialect, "dialect");
        this.prefix = tablePrefix == null ? "csap_apidoc_" : tablePrefix;
        if (!PREFIX.matcher(this.prefix).matches()) {
            throw new IllegalArgumentException("csap.apidoc.database.table-prefix 只能包含字母、数字和下划线: " + tablePrefix);
        }
        if (service == null || service.trim().isEmpty()) {
            throw new IllegalArgumentException("service 不能为空");
        }
        this.service = service.trim();
        this.ruleTable = this.prefix + "rule";
        this.historyTable = this.prefix + "history";
        this.metaTable = this.prefix + "meta";
    }

    @Override
    public String describe() {
        return "dialect=" + dialect + " service=" + service + " tablePrefix=" + prefix;
    }

    @Override
    public void init(boolean createIfMissing, boolean readOnly) throws SQLException {
        if (readOnly) {
            checkSchema();
        } else {
            ensureSchema(createIfMissing);
        }
    }

    public DatabaseDialect dialect() {
        return dialect;
    }

    public DataSource dataSource() {
        return dataSource;
    }

    @Override
    public String service() {
        return service;
    }

    public String tablePrefix() {
        return prefix;
    }

    /**
     * 建表语句(DBA 手工执行时可直接使用)。
     *
     * @param dialect     方言
     * @param tablePrefix 表名前缀
     * @return 语句列表,每条不带分号
     */
    public static List<String> schema(DatabaseDialect dialect, String tablePrefix) {
        List<String> sql = new ArrayList<>();
        schemaByTable(dialect, tablePrefix).values().forEach(sql::addAll);
        return sql;
    }

    /**
     * 建表脚本全文(jar 内 META-INF/csap-apidoc/database/{方言}.sql 就是它的输出,默认表前缀)。
     *
     * @param dialect     方言
     * @param tablePrefix 表名前缀
     * @return 脚本
     */
    public static String schemaScript(DatabaseDialect dialect, String tablePrefix) {
        StringBuilder sb = new StringBuilder();
        sb.append("-- CSAP Apidoc 数据库模式建表脚本 / schema for the database rule store (")
          .append(dialect.name().toLowerCase(Locale.ROOT)).append(")\n")
          .append("-- 与 csap-apidoc-go 共用同一套表;表前缀 csap.apidoc.database.table-prefix 默认 csap_apidoc_\n")
          .append("-- Shared with csap-apidoc-go. Generated by DatabaseRuleStore.schemaScript, do not edit by hand.\n\n");
        for (String sql : schema(dialect, tablePrefix)) {
            sb.append(sql).append(";\n\n");
        }
        sb.append("-- MCP 审计表:只有 csap.apidoc.mcp.audit.store=database 时才使用,规则存储不依赖它\n")
          .append("-- MCP audit table: used only when csap.apidoc.mcp.audit.store=database\n\n");
        for (String sql : mcpAuditSchema(dialect, tablePrefix)) {
            sb.append(sql).append(";\n\n");
        }
        return sb.toString();
    }

    /**
     * MCP 审计表 {prefix}mcp_audit 的建表语句(表 + 两个索引),每条不带分号。
     * 规则存储本身不建这张表,由 csap-apidoc-mcp 在 {@code csap.apidoc.mcp.audit.store=database} 时按需创建。
     *
     * @param dialect     方言
     * @param tablePrefix 表名前缀
     * @return 语句列表
     */
    public static List<String> mcpAuditSchema(DatabaseDialect dialect, String tablePrefix) {
        String p = tablePrefix == null ? "csap_apidoc_" : tablePrefix;
        String text = dialect.textType();
        return Arrays.asList("CREATE TABLE " + p + "mcp_audit (\n"
                + "    " + dialect.idColumn() + ",\n"
                + "    service VARCHAR(128) NOT NULL,\n"
                + "    at BIGINT NOT NULL,\n"
                + "    caller VARCHAR(128),\n"
                + "    remote_address VARCHAR(64),\n"
                + "    tool VARCHAR(128),\n"
                + "    target VARCHAR(512),\n"
                + "    arguments " + text + ",\n"
                + "    status INT NOT NULL,\n"
                + "    success SMALLINT NOT NULL,\n"
                + "    result " + text + ",\n"
                + "    duration_ms BIGINT NOT NULL\n"
                + ")" + dialect.tableOptions(),
                "CREATE INDEX " + p + "mcp_audit_service_at ON " + p + "mcp_audit (service, at)",
                "CREATE INDEX " + p + "mcp_audit_at ON " + p + "mcp_audit (at)");
    }

    /**
     * 按表分组的建表语句:rule、history、meta。
     */
    private static Map<String, List<String>> schemaByTable(DatabaseDialect dialect, String tablePrefix) {
        String p = tablePrefix == null ? "csap_apidoc_" : tablePrefix;
        String text = dialect.textType();
        String opts = dialect.tableOptions();
        Map<String, List<String>> out = new LinkedHashMap<>();
        out.put("rule", Collections.singletonList("CREATE TABLE " + p + "rule (\n"
                + "    service VARCHAR(128) NOT NULL,\n"
                + "    rule_key VARCHAR(512) NOT NULL,\n"
                + "    rules " + text + " NOT NULL,\n"
                + "    version BIGINT NOT NULL,\n"
                + "    updated_by VARCHAR(128) NOT NULL,\n"
                + "    updated_at BIGINT NOT NULL,\n"
                + "    PRIMARY KEY (service, rule_key)\n"
                + ")" + opts));
        out.put("history", Arrays.asList("CREATE TABLE " + p + "history (\n"
                + "    " + dialect.idColumn() + ",\n"
                + "    service VARCHAR(128) NOT NULL,\n"
                + "    rule_key VARCHAR(512) NOT NULL,\n"
                + "    before_rules " + text + ",\n"
                + "    after_rules " + text + ",\n"
                + "    version BIGINT NOT NULL,\n"
                + "    updated_by VARCHAR(128) NOT NULL,\n"
                + "    updated_at BIGINT NOT NULL\n"
                + ")" + opts,
                "CREATE INDEX " + p + "history_key ON " + p + "history (service, rule_key, id)"));
        out.put("meta", Collections.singletonList("CREATE TABLE " + p + "meta (\n"
                + "    service VARCHAR(128) NOT NULL PRIMARY KEY,\n"
                + "    version BIGINT NOT NULL\n"
                + ")" + opts));
        return out;
    }

    /**
     * 表不存在时建表,并确保本服务的版本号行存在。
     *
     * @param createTables 是否允许建表;不允许且表不存在时报错
     */
    public void ensureSchema(boolean createTables) throws SQLException {
        try (Connection conn = dataSource.getConnection()) {
            boolean autoCommit = conn.getAutoCommit();
            conn.setAutoCommit(true);
            try {
                checkLegacy(conn);
                for (Map.Entry<String, List<String>> e : schemaByTable(dialect, prefix).entrySet()) {
                    String table = prefix + e.getKey();
                    if (probe(conn, "SELECT 1 FROM " + table + " WHERE 1 = 0")) {
                        continue;
                    }
                    if (!createTables) {
                        throw missingTable(table);
                    }
                    try (Statement st = conn.createStatement()) {
                        for (String sql : e.getValue()) {
                            st.execute(sql);
                        }
                    } catch (SQLException ex) {
                        // 多个实例同时启动:别的实例刚建好,忽略
                        if (!probe(conn, "SELECT 1 FROM " + table + " WHERE 1 = 0")) {
                            throw ex;
                        }
                    }
                }
                ensureMetaRow(conn);
            } finally {
                conn.setAutoCommit(autoCommit);
            }
        }
    }

    /**
     * 只读检查:表必须已经存在,不建表、不写版本号行。
     */
    public void checkSchema() throws SQLException {
        try (Connection conn = dataSource.getConnection()) {
            checkLegacy(conn);
            for (String name : schemaByTable(dialect, prefix).keySet()) {
                String table = prefix + name;
                if (!probe(conn, "SELECT 1 FROM " + table + " WHERE 1 = 0")) {
                    throw missingTable(table);
                }
            }
        }
    }

    private IllegalStateException missingTable(String table) {
        return new IllegalStateException("规则表 " + table + " 不存在。请先执行建表 SQL(jar 内 META-INF/csap-apidoc/database/"
                + dialect.name().toLowerCase(Locale.ROOT) + ".sql),或设置 csap.apidoc.database.init-schema=true 让应用自动建表"
                + "(只读模式不建表)。");
    }

    private void checkLegacy(Connection conn) {
        if (!probe(conn, "SELECT service FROM " + ruleTable + " WHERE 1 = 0")
                && probe(conn, "SELECT rule_key FROM " + ruleTable + " WHERE 1 = 0")) {
            throw new IllegalStateException("表 " + ruleTable + " 已存在但没有 service 列,可能是 csap-apidoc-go v0.1.x 建的旧表。"
                    + "请按升级说明加上 service 列(见官网“数据库模式”页),或改用新的 table-prefix。");
        }
    }

    private static boolean probe(Connection conn, String sql) {
        try (Statement st = conn.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            return true;
        } catch (SQLException e) {
            return false;
        }
    }

    private void ensureMetaRow(Connection conn) throws SQLException {
        if (readVersion(conn) != null) {
            return;
        }
        try (PreparedStatement ps = conn.prepareStatement("INSERT INTO " + metaTable + " (service, version) VALUES (?, ?)")) {
            ps.setString(1, service);
            ps.setLong(2, 0L);
            ps.executeUpdate();
        } catch (SQLException e) {
            // 多个实例同时启动:别的实例已经插入,忽略
            if (readVersion(conn) == null) {
                throw e;
            }
        }
    }

    private Long readVersion(Connection conn) throws SQLException {
        try (PreparedStatement ps = conn.prepareStatement("SELECT version FROM " + metaTable + " WHERE service = ?")) {
            ps.setString(1, service);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? rs.getLong(1) : null;
            }
        }
    }

    /**
     * 本服务的全局版本号,没有记录时为 0。
     */
    @Override
    public long version() throws SQLException {
        try (Connection conn = dataSource.getConnection()) {
            Long v = readVersion(conn);
            return v == null ? 0L : v;
        }
    }

    /**
     * 读取本服务的全部规则。先读版本号再读规则:两者之间若有修改,记下的版本偏旧,下次检查会再加载一次,不会漏。
     */
    @Override
    public Snapshot load() throws SQLException {
        try (Connection conn = dataSource.getConnection()) {
            Long v = readVersion(conn);
            Map<String, String> rules = new LinkedHashMap<>();
            try (PreparedStatement ps = conn.prepareStatement(
                    "SELECT rule_key, rules FROM " + ruleTable + " WHERE service = ? ORDER BY rule_key")) {
                ps.setString(1, service);
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        rules.put(rs.getString(1), rs.getString(2));
                    }
                }
            }
            return new RuleStore.Snapshot(v == null ? 0L : v, rules);
        }
    }

    /**
     * 保存一个接口的规则:一个事务内全局版本号加 1(行锁串行化并发保存)、写规则、写修改记录。
     *
     * @param ruleKey   规则键(类名.方法名 / 分组.接口名)
     * @param rulesJson 规则 JSON,null 表示删除
     * @param updatedBy 修改人
     * @return 新版本号;内容与库里相同、没有修改时返回 -1
     */
    @Override
    public long save(String ruleKey, String rulesJson, String updatedBy) throws SQLException {
        String by = updatedBy == null || updatedBy.isEmpty() ? "unknown" : updatedBy;
        try (Connection conn = dataSource.getConnection()) {
            boolean autoCommit = conn.getAutoCommit();
            conn.setAutoCommit(false);
            try {
                long v = bumpVersion(conn);
                String before = null;
                boolean exists = false;
                try (PreparedStatement ps = conn.prepareStatement(
                        "SELECT rules FROM " + ruleTable + " WHERE service = ? AND rule_key = ?")) {
                    ps.setString(1, service);
                    ps.setString(2, ruleKey);
                    try (ResultSet rs = ps.executeQuery()) {
                        if (rs.next()) {
                            exists = true;
                            before = rs.getString(1);
                        }
                    }
                }
                if (RuleJson.sameJson(before, rulesJson)) {
                    conn.rollback();
                    return -1L;
                }
                long now = System.currentTimeMillis();
                if (rulesJson == null) {
                    try (PreparedStatement ps = conn.prepareStatement(
                            "DELETE FROM " + ruleTable + " WHERE service = ? AND rule_key = ?")) {
                        ps.setString(1, service);
                        ps.setString(2, ruleKey);
                        ps.executeUpdate();
                    }
                } else if (exists) {
                    try (PreparedStatement ps = conn.prepareStatement("UPDATE " + ruleTable
                            + " SET rules = ?, version = ?, updated_by = ?, updated_at = ? WHERE service = ? AND rule_key = ?")) {
                        ps.setString(1, rulesJson);
                        ps.setLong(2, v);
                        ps.setString(3, by);
                        ps.setLong(4, now);
                        ps.setString(5, service);
                        ps.setString(6, ruleKey);
                        ps.executeUpdate();
                    }
                } else {
                    try (PreparedStatement ps = conn.prepareStatement("INSERT INTO " + ruleTable
                            + " (service, rule_key, rules, version, updated_by, updated_at) VALUES (?, ?, ?, ?, ?, ?)")) {
                        ps.setString(1, service);
                        ps.setString(2, ruleKey);
                        ps.setString(3, rulesJson);
                        ps.setLong(4, v);
                        ps.setString(5, by);
                        ps.setLong(6, now);
                        ps.executeUpdate();
                    }
                }
                try (PreparedStatement ps = conn.prepareStatement("INSERT INTO " + historyTable
                        + " (service, rule_key, before_rules, after_rules, version, updated_by, updated_at)"
                        + " VALUES (?, ?, ?, ?, ?, ?, ?)")) {
                    ps.setString(1, service);
                    ps.setString(2, ruleKey);
                    ps.setString(3, before);
                    ps.setString(4, rulesJson);
                    ps.setLong(5, v);
                    ps.setString(6, by);
                    ps.setLong(7, now);
                    ps.executeUpdate();
                }
                conn.commit();
                return v;
            } catch (SQLException | RuntimeException e) {
                try {
                    conn.rollback();
                } catch (SQLException suppressed) {
                    e.addSuppressed(suppressed);
                }
                throw e;
            } finally {
                conn.setAutoCommit(autoCommit);
            }
        }
    }

    /**
     * 先 UPDATE 加版本号:MySQL / PostgreSQL / 达梦 / 金仓会锁住该行,并发保存因此串行化。
     */
    private long bumpVersion(Connection conn) throws SQLException {
        int updated;
        try (PreparedStatement ps = conn.prepareStatement(
                "UPDATE " + metaTable + " SET version = version + 1 WHERE service = ?")) {
            ps.setString(1, service);
            updated = ps.executeUpdate();
        }
        if (updated == 0) {
            try (PreparedStatement ps = conn.prepareStatement("INSERT INTO " + metaTable + " (service, version) VALUES (?, ?)")) {
                ps.setString(1, service);
                ps.setLong(2, 1L);
                ps.executeUpdate();
            }
            return 1L;
        }
        Long v = readVersion(conn);
        if (v == null) {
            throw new SQLException("版本号行丢失: " + metaTable + " service=" + service);
        }
        return v;
    }

    /**
     * 修改记录,最新的在前。
     *
     * @param ruleKey 规则键,null 或空字符串表示全部
     * @param limit   条数,小于等于 0 时为 100
     */
    @Override
    public List<RuleChange> history(String ruleKey, int limit) throws SQLException {
        boolean all = ruleKey == null || ruleKey.isEmpty();
        String sql = "SELECT id, rule_key, before_rules, after_rules, version, updated_by, updated_at FROM " + historyTable
                + " WHERE service = ?" + (all ? "" : " AND rule_key = ?") + " ORDER BY id DESC";
        List<RuleChange> out = new ArrayList<>();
        try (Connection conn = dataSource.getConnection(); PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setMaxRows(limit <= 0 ? 100 : limit);
            ps.setString(1, service);
            if (!all) {
                ps.setString(2, ruleKey);
            }
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    out.add(new RuleChange(rs.getLong(1), rs.getString(2), rs.getString(3), rs.getString(4),
                            rs.getLong(5), rs.getString(6), rs.getLong(7)));
                }
            }
        }
        return out;
    }

    /**
     * 把某条修改记录对应的接口恢复成"修改前"的样子。回滚本身也是一次保存,会留下新的记录。
     *
     * @return 新版本号;已经是修改前的内容时返回 -1
     * @throws IllegalArgumentException 修改记录不存在(或不属于本服务)
     */
    @Override
    public long rollback(long changeId, String updatedBy) throws SQLException {
        String key;
        String before;
        try (Connection conn = dataSource.getConnection(); PreparedStatement ps = conn.prepareStatement(
                "SELECT rule_key, before_rules FROM " + historyTable + " WHERE id = ? AND service = ?")) {
            ps.setLong(1, changeId);
            ps.setString(2, service);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    throw new IllegalArgumentException("修改记录不存在: " + changeId);
                }
                key = rs.getString(1);
                before = rs.getString(2);
            }
        }
        return save(key, before, updatedBy);
    }
}
